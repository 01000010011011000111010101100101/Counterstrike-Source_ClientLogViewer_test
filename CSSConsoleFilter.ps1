function appendSpaces([string]$t) {
	while ($t.Length -lt ($global:cmdLineWidth / 2 - 3)) {
		$t = $t + " "
	}			
	return $t
}
#-----------------------------------------------------------------------------------------------------------
function appendHyphen([string]$t) {
	while ($t.Length -lt ($global:cmdLineWidth / 2 - 3)) {
		$t = $t + "-"
	}			
	return $t

}
